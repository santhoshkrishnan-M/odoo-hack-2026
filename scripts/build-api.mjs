// Bundles the Express API into api/index.js for Vercel Functions (run by `npm run build`).
// Not needed for local use: `npm run dev` and `npm start` run the TypeScript directly.
import { build } from 'esbuild';
await build({
  entryPoints: ['server/src/vercel.ts'], bundle: true, platform: 'node', format: 'esm', target: 'node22', packages: 'external',
  outfile: 'api/index.js', legalComments: 'none',
  banner: { js: '// Generated by scripts/build-api.mjs from server/src — do not edit by hand.' },
});
console.log('api/index.js built');
